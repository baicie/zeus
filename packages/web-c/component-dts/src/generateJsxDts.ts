import {
  formatDetailType,
  formatPropType,
  isRequiredProp,
  safePropertyName,
} from './formatType'
import { generatePropTypeDeclarations } from './generatePropTypeDeclarations'
import { getGeneratedDeclarationNames, getPropsTypeName } from './naming'

import type {
  ComponentManifest,
  ComponentRecord,
} from '@zeus-js/component-analyzer'

export function generateWCJsxDts(manifest: ComponentManifest): string {
  const lines: string[] = []

  lines.push('/* eslint-disable */')
  lines.push('// Generated by @zeus-js/component-dts.')
  lines.push('')
  const reservedNames = getGeneratedDeclarationNames(manifest.components)
  reservedNames.add('JSX')
  const propTypeDeclarations = generatePropTypeDeclarations(
    manifest.components,
    { reservedNames },
  )
  if (propTypeDeclarations.code) {
    lines.push(propTypeDeclarations.code)
    lines.push('')
  }

  for (const component of propTypeDeclarations.components) {
    lines.push(generateComponentJsxProps(component))
    lines.push('')
  }

  lines.push("declare module '@zeus-js/zeus/jsx' {")
  lines.push('  namespace JSX {')
  lines.push('    interface IntrinsicElements {')

  for (const component of manifest.components) {
    lines.push(
      `      ${JSON.stringify(component.tag)}: ${getPropsTypeName(component)}`,
    )
  }

  lines.push('    }')
  lines.push('  }')
  lines.push('}')
  lines.push('')
  lines.push('export {}')
  lines.push('')

  return lines.join('\n')
}

function generateComponentJsxProps(component: ComponentRecord): string {
  const propsTypeName = getPropsTypeName(component)
  const lines: string[] = []

  lines.push(`export type ${propsTypeName} = {`)

  for (const [name, prop] of Object.entries(component.props)) {
    const optional = isRequiredProp(prop) ? '' : '?'
    lines.push(
      `  ${safePropertyName(name)}${optional}: ${formatPropType(prop)}`,
    )
  }

  for (const [key, event] of Object.entries(component.events)) {
    const detailType = event.detail
      ? formatDetailType(event.detail, event.detailOptional)
      : 'unknown'
    lines.push(
      `  ${safePropertyName(event.reactName ?? toReactEventProp(event.key ?? key))}?: (event: CustomEvent<${detailType}>) => void`,
    )
  }

  lines.push('')
  /*
   * Props every Zeus element accepts, whatever its own schema says.
   *
   * `ref` belongs here for the same reason `class` does: it is a binding the
   * compiler understands on any element, not a property of one component. It
   * was missing until R6-C, which meant every `ref={...}` on a `zw-*` element
   * was a type error — invisible as long as no consumer ran `tsc` over those
   * call sites, and a blocker the moment one did.
   *
   * The type is Zeus's own `RefTarget`, resolved through the JSX runtime rather
   * than restated here, so it cannot drift from what the compiler accepts.
   */
  const commonProps = {
    children: 'unknown',
    class: 'string',
    className: 'string',
    style: 'string | Record<string, string | number | null | undefined>',
    id: 'string',
    role: 'string',
    part: 'string',
    slot: 'string',
    // Written inline rather than as `RefTarget` from another package: these
    // declarations are consumed by projects that do not depend on
    // `@zeus-js/runtime-dom`, and a generated file that imports it does not
    // resolve for them. The shape is what the compiler accepts — a callback
    // receiving the element — and it is the same shape `RefTarget` describes.
    ref: '((element: HTMLElement | null) => void) | null',
  }
  for (const [name, type] of Object.entries(commonProps)) {
    // Component schemas can refine common attributes, including requiredness.
    if (!Object.prototype.hasOwnProperty.call(component.props, name)) {
      lines.push(`  ${name}?: ${type}`)
    }
  }
  lines.push('')
  lines.push('  [key: `data-${string}`]: unknown')
  lines.push('  [key: `aria-${string}`]: unknown')
  lines.push('}')

  return lines.join('\n')
}

function toReactEventProp(value: string): string {
  return `on${value
    .split('-')
    .filter(Boolean)
    .map(part => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join('')}`
}
